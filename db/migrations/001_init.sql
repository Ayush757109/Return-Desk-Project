-- ReturnDesk — initial schema (PostgreSQL 14+)
--
-- This file is the source-of-truth schema for a clean deployment.
-- Run it once against an empty database, then run scripts/seed.mjs.
--
-- Design notes:
-- * Reasons / statuses / resolutions are TEXT + CHECK (not native ENUMs) so
--   values stay readable in API payloads and new values do not need
--   ALTER TYPE migrations. The API validates the same value sets.
-- * Rule 3 (one live request per order + item) is backed by a PARTIAL
--   UNIQUE INDEX, which is the only race-free way to enforce it: two
--   concurrent INSERTs for the same (order_id, item_sku) cannot both win.
--   Comparison is case-insensitive via lower(trim(...)) functional keys.
-- * Rule 2 (refund coherence) is also expressed as CHECK constraints so
--   even hand-written SQL cannot store an incoherent approval.
-- * Soft removal (Rule 5) uses deleted_at; rows are never hard-deleted
--   by the application. return_notes cascade only protects against a
--   manual hard delete in SQL — the API exposes no such operation.

begin;

create table if not exists return_requests (
  id            bigint generated by default as identity primary key,
  reference     text        not null unique,
  customer_name text        not null check (char_length(btrim(customer_name)) > 0),
  customer_email text       not null check (customer_email like '%@%.%'),
  customer_phone text,
  order_id      text        not null check (char_length(btrim(order_id)) > 0),
  item_name     text        not null check (char_length(btrim(item_name)) > 0),
  item_sku      text        not null check (char_length(btrim(item_sku)) > 0),
  quantity      integer     not null default 1 check (quantity >= 1 and quantity <= 999),
  reason        text        not null check (reason in ('Damaged', 'Wrong Item', 'Size Issue', 'Not As Described', 'Changed Mind')),
  status        text        not null default 'Open'
                check (status in ('Open', 'In Review', 'Approved', 'Rejected', 'Completed')),
  resolution    text        check (resolution in ('Refund', 'Replacement', 'Store Credit')),
  refund_amount numeric(10, 2),
  deleted_at    timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),

  -- Rule 2a: Approved/Completed must carry a resolution; earlier and
  -- Rejected states must not.
  constraint resolution_matches_status check (
    (status in ('Approved', 'Completed') and resolution is not null)
    or (status in ('Open', 'In Review', 'Rejected') and resolution is null)
  ),
  -- Rule 2b: Refund requires amount > 0; every other case must be NULL.
  constraint refund_amount_coherent check (
    (resolution = 'Refund' and refund_amount is not null and refund_amount > 0)
    or (resolution is distinct from 'Refund' and refund_amount is null)
  )
);

create table if not exists return_notes (
  id         bigint generated by default as identity primary key,
  request_id bigint      not null references return_requests (id) on delete cascade,
  author     text        not null default 'Support Agent',
  body       text        not null check (char_length(btrim(body)) > 0),
  created_at timestamptz not null default now()
);

-- Rule 3: at most one LIVE (Open / In Review / Approved, not soft-deleted)
-- request per (order, item). Rejected / Completed / soft-deleted rows do
-- not participate, so a customer can re-request after a final outcome.
create unique index if not exists return_requests_one_live_per_order_item
  on return_requests (lower(btrim(order_id)), lower(btrim(item_sku)))
  where status in ('Open', 'In Review', 'Approved') and deleted_at is null;

-- Queue access paths: list filtering/sorting and the notes timeline.
create index if not exists return_requests_visible_created_idx
  on return_requests (created_at desc) where deleted_at is null;
create index if not exists return_requests_status_idx
  on return_requests (status) where deleted_at is null;
create index if not exists return_notes_request_created_idx
  on return_notes (request_id, created_at asc, id asc);

-- Substring search (customer / email / order / reference) uses ILIKE.
-- pg_trgm keeps those lookups indexed once the desk grows; optional but
-- recommended. Safe to skip on providers without the extension.
create extension if not exists pg_trgm;
create index if not exists return_requests_customer_name_trgm_idx
  on return_requests using gin (customer_name gin_trgm_ops);
create index if not exists return_requests_customer_email_trgm_idx
  on return_requests using gin (customer_email gin_trgm_ops);
create index if not exists return_requests_order_id_trgm_idx
  on return_requests using gin (order_id gin_trgm_ops);
create index if not exists return_requests_reference_trgm_idx
  on return_requests using gin (reference gin_trgm_ops);

-- Keep updated_at honest even for hand-written SQL (the API also sets it).
create or replace function set_updated_at() returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists return_requests_set_updated_at on return_requests;
create trigger return_requests_set_updated_at
  before update on return_requests
  for each row execute function set_updated_at();

commit;
